"""Complete, deterministic source plans for the retained generated C++ tree."""

from __future__ import annotations

import hashlib
import json
from collections.abc import Iterable
from dataclasses import asdict
from importlib.resources import files as package_files
from pathlib import Path, PurePosixPath

from udb.architecture import ConfiguredArchitecture
from udb.authoring import AuthoringPlan, GeneratedFile

from . import c_api, csrs, functions, hart, instructions, shared
from .catalog import Catalog
from .context import Context
from .resources import RuntimeResources, standalone_cmake
from .types import CppGenerationError, identifier

OWNER = "cpp-hart-source"
BANNER = """// Generated by udb.cpp_hart; do not edit.
// SPDX-FileCopyrightText: Qualcomm Technologies, Inc. and/or its subsidiaries
// SPDX-FileCopyrightText: 2026 Contributors to the RISCV UnifiedDB <https://github.com/riscv/riscv-unified-db>
// SPDX-License-Identifier: BSD-3-Clause-Clear

"""
BUILD_TYPES = ("Debug", "RelWithDebInfo", "Release", "Asan")
SHARED_ARTIFACTS = (
    "include/udb/hart_factory.hxx",
    "include/udb/db_data.hxx",
    "src/db_data.cxx",
    "include/udb/enum.hxx",
    "src/enum.cxx",
    "include/udb/bitfield.hxx",
    "include/udb/libhart.h",
)
CONFIG_ARTIFACTS = (
    "inst.hxx",
    "inst_impl.hxx",
    "params.hxx",
    "hart.hxx",
    "hart_impl.hxx",
    "csrs.hxx",
    "csrs_impl.hxx",
    "csr_container.hxx",
    "structs.hxx",
    "func_prototypes.hxx",
    "idl_funcs_impl.hxx",
)


def build_type(value: str) -> str:
    aliases = {
        "DEBUG": "Debug",
        "FAST_DEBUG": "RelWithDebInfo",
        "RELWITHDEBINFO": "RelWithDebInfo",
        "RELEASE": "Release",
        "ASAN": "Asan",
    }
    try:
        return aliases[value.upper()]
    except (AttributeError, KeyError) as error:
        raise CppGenerationError(f"Build type must be one of {', '.join(BUILD_TYPES)}") from error


def _hash(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def _json(value) -> bytes:
    return (json.dumps(value, sort_keys=True, ensure_ascii=True, indent=2) + "\n").encode("utf-8")


def _implementation_hashes():
    package = package_files("udb")
    inputs = {}

    def collect(directory, prefix):
        for file in sorted(directory.iterdir(), key=lambda file: file.name):
            if file.is_dir() and file.name != "__pycache__":
                collect(file, prefix + file.name + "/")
            elif file.is_file() and file.name.endswith(".py"):
                inputs[prefix + file.name] = _hash(file.read_bytes())

    for subsystem in ("idl", "cpp_hart"):
        collect(package.joinpath(subsystem), f"implementation/udb/{subsystem}/")
    for name in (
        "architecture",
        "authoring",
        "configuration",
        "database",
        "conditions",
        "idl_architecture",
        "idl_environment",
        "idl_csr_environment",
        "idl_condition_binding",
        "instruction_fields",
        "versions",
    ):
        file = package.joinpath(name + ".py")
        inputs[f"implementation/udb/{name}.py"] = _hash(file.read_bytes())
    return inputs


def _unavailable(contexts):
    return [
        {"configuration": context.name, **asdict(item)}
        for context in contexts
        for item in context.unavailable
    ]


class CppHartGenerator:
    """Generate sources only: no compiler, native tool, shell, or network calls.

    Architectures are already resolved/configured through the public database API.
    Resources are packaged or explicitly declared by the caller. A plan writes a
    complete standalone tree at its caller-chosen root.
    """

    def __init__(
        self,
        architectures: Iterable[ConfiguredArchitecture],
        *,
        resources: RuntimeResources | None = None,
        build_name: str | None = None,
        build_type: str = "RelWithDebInfo",
    ):
        architectures = tuple(architectures)
        if not architectures or any(
            not isinstance(arch, ConfiguredArchitecture) for arch in architectures
        ):
            raise TypeError("C++ generation requires one or more ConfiguredArchitecture inputs")
        self.names = tuple(arch.configuration.name for arch in architectures)
        if len(set(self.names)) != len(self.names):
            raise CppGenerationError("Configuration names must be unique")
        if len(self.names) > 1 and build_name is None:
            raise CppGenerationError("A build name is required for multiple configurations")
        self.build_name = build_name or self.names[0]
        identifier(self.build_name)
        self.build_type = globals()["build_type"](build_type)
        self.architectures = architectures
        self.resources = resources if resources is not None else RuntimeResources.bundled()

    @property
    def directory_name(self):
        return f"{self.build_name}_{self.build_type}"

    def plan(self) -> AuthoringPlan:
        contexts = tuple(Context(arch) for arch in self.architectures)
        first = contexts[0]
        catalog = Catalog(contexts)
        symbols = tuple(context.symbol("hart") for context in contexts)
        if len(set(symbols)) != len(symbols):
            raise CppGenerationError("Configuration names collide after C++ name conversion")
        outputs: dict[str, tuple[bytes, int]] = {}
        input_hashes: dict[str, str] = _implementation_hashes()

        def add(path, content, mode=0o644):
            if path in outputs:
                raise CppGenerationError(f"Duplicate generated artifact {path}")
            if isinstance(content, str):
                if PurePosixPath(path).suffix in {".h", ".hxx", ".cxx"}:
                    content = BANNER + content
                content = content.encode("utf-8")
            outputs[path] = (content, mode)

        for path, content, mode, origin in self.resources.files():
            input_hashes["runtime/" + str(origin)] = _hash(content)
            if str(path) == "CMakeLists.txt":
                content = standalone_cmake(content, self.names, self.build_type)
            add(str(path), content, mode)
        notice = package_files("udb.cpp_hart").joinpath("NOTICE").read_bytes()
        input_hashes["implementation/udb/cpp_hart/NOTICE"] = _hash(notice)
        add("NOTICE_CPP_HART", notice)
        schema_root = first.database.schemas_root
        if schema_root is None:
            raise CppGenerationError(
                "Native database metadata requires an explicit or bundled schema root"
            )
        schemas = {}
        for file in sorted(schema_root.iterdir(), key=lambda file: file.name):
            if (
                file.is_file()
                and file.name.endswith(".json")
                and (file.name == "schema_defs.json" or file.name.startswith("config"))
            ):
                text = file.read_bytes()
                input_hashes["schemas/" + file.name] = _hash(text)
                schemas[file.name] = text.decode("utf-8")
        if "schema_defs.json" not in schemas or "config_schema.json" not in schemas:
            raise CppGenerationError(
                "Native resources require schema_defs.json and config_schema.json"
            )
        enum_header, enum_source = shared.enums(catalog)
        db_header, db_source = shared.database_data(catalog, schemas)
        shared_outputs = (
            shared.factory(contexts),
            db_header,
            db_source,
            enum_header,
            enum_source,
            shared.bitfields(catalog),
            c_api.header(catalog),
        )
        for path, content in zip(SHARED_ARTIFACTS, shared_outputs, strict=True):
            add(path, content)
        # The legacy source exists and is retained for direct Renode consumers,
        # although the old task neglected to schedule its generation.
        add("include/udb/libhart_renode.h", c_api.header(catalog, renode=True))
        for context in contexts:
            prefix = f"include/udb/cfgs/{context.name}/"
            inst, inst_impl = instructions.instruction_headers(context)
            csr, csr_impl = csrs.csr_headers(context)
            prototypes, defs = functions.function_headers(context)
            contents = (
                inst,
                inst_impl,
                shared.parameters(context),
                hart.hart_header(context),
                hart.hart_implementation(context),
                csr,
                csr_impl,
                csrs.csr_container(context),
                shared.structs(context),
                prototypes,
                defs,
            )
            for name, text in zip(CONFIG_ARTIFACTS, contents, strict=True):
                add(prefix + name, text)
            cfg_data = context.arch.configuration.to_dict()
            input_hashes[f"configs/{context.name}.json"] = _hash(_json(cfg_data))
            if context.arch.configuration.source_text is not None:
                input_hashes[f"configs/{context.name}.source-text.utf8"] = _hash(
                    context.arch.configuration.source_text.encode("utf-8")
                )
            for record in context.database.objects():
                input_hashes[f"{context.name}/records/{record.path}"] = _hash(
                    _json(record.to_dict())
                )
            for (layer, path), source in context.database.idl_source_layers.items():
                input_hashes[f"{context.name}/idl/{layer}/{path}"] = _hash(
                    source.text.encode("utf-8")
                )
            add(f"cfgs/{context.name}.json", _json(cfg_data))
        manifest = {
            "format": 1,
            "generator": OWNER,
            "build_name": self.build_name,
            "build_type": self.build_type,
            "configurations": list(self.names),
            "inputs": dict(sorted(input_hashes.items())),
            "outputs": {
                name: {"sha256": _hash(content), "mode": mode}
                for name, (content, mode) in sorted(outputs.items())
            },
            "unavailable": _unavailable(contexts),
        }
        add("cpp-hart-manifest.json", _json(manifest))
        # The plan owns an in-memory, fully hashed database/resource snapshot.
        # One content-addressed logical dependency keeps the writer's alias
        # checks bounded; every individual input remains in the manifest.
        dependencies = (PurePosixPath(".cpp_hart_inputs") / f"{_hash(_json(input_hashes))}.json",)
        return AuthoringPlan(
            tuple(
                GeneratedFile(PurePosixPath(path), content, OWNER, dependencies, mode)
                for path, (content, mode) in sorted(outputs.items())
            )
        )

    def generate(self, root: str | Path, *, check: bool = False):
        root = Path(root)
        if isinstance(self.resources.root, Path):
            for output, _, _, origin in self.resources.files():
                source = self.resources.root / origin
                target = root / output
                if target.resolve() == source.resolve() or (
                    target.exists() and source.exists() and target.samefile(source)
                ):
                    raise CppGenerationError(f"Generated output aliases runtime source: {target}")
        return self.plan().apply(root, check=check)
