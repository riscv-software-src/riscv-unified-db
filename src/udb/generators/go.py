"""Go cmd/internal/obj encoder source, retaining the original generator ABI."""

from collections.abc import Sequence

from .encoding_inputs import (
    GO_EXTENSIONS,
    EncodingGeneratorError,
    EncodingSource,
    TargetArch,
    build_encoding_inputs,
    identifier,
    normalize_extensions,
)


def generate_go(
    source: EncodingSource,
    *,
    extensions: str | Sequence[str] = GO_EXTENSIONS,
    include_all: bool = False,
    arch: TargetArch = "RV64",
) -> str:
    """Return unformatted source for Go's RISC-V assembler package.

    As in the native script, an empty extension list disables filtering. The
    caller supplies its assembler's ``A<INSTRUCTION>`` obj.As constants; this is
    not a standalone replacement for the cmd/internal/obj assembler package.
    No gofmt or other executable is needed to generate the artifact.
    """
    inputs = build_encoding_inputs(
        source,
        extensions=extensions,
        include_all=include_all or not normalize_extensions(extensions),
        arch=arch,
    )
    if not inputs.instructions:
        raise EncodingGeneratorError("No instructions found or all were filtered out.")
    prelude = """// Code generated by udb.generators.go; DO NOT EDIT.
package riscv

import "cmd/internal/obj"

type inst struct {
\topcode uint32
\tfunct3 uint32
\trs1    uint32
\trs2    uint32
\tcsr    int64
\tfunct7 uint32
}

func encode(a obj.As) *inst {
\tswitch a {
"""
    lines = [prelude]
    seen: set[str] = set()
    for encoding in sorted(inputs.instructions, key=lambda item: item.name.upper()):
        name = identifier("A" + encoding.name.upper().replace(".", ""), "Go instruction identifier")
        if name in seen:
            raise EncodingGeneratorError(f"Go instruction identifier collision: {name}")
        seen.add(name)
        match = encoding.value
        opcode = match & 0x7F
        funct3 = (match >> 12) & 7
        rs1 = (match >> 15) & 31
        rs2 = (match >> 20) & 31
        csr = (match >> 20) & 0xFFF
        if csr >= 0x800:
            csr -= 0x1000
        funct7 = (match >> 25) & 0x7F
        lines.append(
            f"  case {name}:\n"
            f"    return &inst{{ {hex(opcode)}, {hex(funct3)}, {hex(rs1)}, "
            f"{hex(rs2)}, {csr}, {hex(funct7)} }}\n"
        )
    lines.append("  }\n\treturn nil\n}\n\nvar csrs = map[uint16]string {\n")
    for address, name in inputs.csrs:
        if address > 0xFFFF:
            raise EncodingGeneratorError("Go CSR addresses must fit uint16")
        identifier(name.replace(".", "_"), "CSR identifier")
        lines.append(f'{hex(address)} : "{name}",\n')
    lines.append("}\n")
    return "".join(lines)


